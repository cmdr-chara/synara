/// Port of `isProductAnalyticsCommand`: set membership on the exact string
/// (UTF-16 marker strings count).
pub fn is_product_analytics_command(value: Value) -> Result<bool, String> {
    let Some(units) = crate::js::string_units(&value) else {
        return Ok(false);
    };
    let Ok(s) = String::from_utf16(&units) else {
        return Ok(false);
    };
    Ok(COMMANDS.contains(&s.as_str()))
}
